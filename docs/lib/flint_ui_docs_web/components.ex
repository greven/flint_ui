    assigns = assign(assigns, :size, size)

    {rest_style, rest} = Map.pop(assigns.rest, :style)

    root_attrs =
      %{
        "data-heading" => true,
        "data-typography" => true,
        "data-size" => assigns.size,
        "data-color" => assigns.data_color,
        "data-weight" => assigns.weight,
        "data-align" => assigns.align,
        "data-truncate" => assigns.truncate and is_nil(assigns.line_clamp),
        "data-line-clamp" => assigns.line_clamp,
        "class" => assigns.class
      }
      |> Enum.reject(fn {_key, value} -> is_nil(value) or value == false or value == "" end)
      |> Map.new()
      |> FlintUI.Styled.Size.put_style(rest_style)
      |> FlintUI.Styled.Size.put_style(heading_line_clamp_style(assigns.line_clamp))

    assigns =
      assigns
      |> assign(:root_attrs, root_attrs)
      |> assign(:rest, rest)

    ~H"""
    <FlintUI.heading root_attrs={@root_attrs} {@rest}>
      <:kicker :if={@kicker != []}>{render_slot(@kicker)}</:kicker>
      {render_slot(@inner_block)}
      <:subtitle :if={@subtitle != []}>{render_slot(@subtitle)}</:subtitle>
    </FlintUI.heading>
    """
  end

  defp heading_level_size("h1"), do: "5xl"
  defp heading_level_size("h2"), do: "4xl"
  defp heading_level_size("h3"), do: "3xl"
  defp heading_level_size("h4"), do: "2xl"
  defp heading_level_size("h5"), do: "xl"
  defp heading_level_size("h6"), do: "lg"
  defp heading_level_size(_), do: "4xl"

  defp heading_line_clamp_style(nil), do: nil
  defp heading_line_clamp_style(lines), do: "--fl-heading-line-clamp: #{lines}"

  @doc """
  Renders a styled text block or link.

  Generated by `mix flint.add text`. Theming lives in `flint.css`; this wrapper
  maps `size`, `color`, `weight`, `align`, `truncate`, and `line_clamp` onto the
  typography hooks the theme targets, and forwards `as` or the link attributes to
  the headless component. `line_clamp` wins over `truncate`. An `external` link
  gets a trailing arrow from `external_icon`, which defaults to
  `lucide-arrow-up-right`. Headless behavior comes from `FlintUI.text`.
  """
  attr(:external_icon, :string,
    default: "lucide-arrow-up-right",
    doc:
      "The icon class for the external-link arrow. Set it to a class from your icon set, or to an empty string to keep the `data-external` hook without an arrow."
  )

  attr(:size, :string,
    values: ~w(xs sm md lg xl 2xl 3xl 4xl 5xl 6xl),
    default: "md",
    doc: "The text size, from the shared type scale."
  )

  attr(:color, :string,
    default: "default",
    doc:
      "The text ink: a text tier such as `default` or `toned`, a semantic role such as `primary` or `danger`, or a raw CSS color such as `#1D72FE`. `dimmed` is below AA and belongs to decoration only. A link in the default tier uses the primary ink. Semantic roles: default, highlighted, toned, muted, dimmed, inverted, neutral, info, success, warning, danger, primary, secondary."
  )

  attr(:weight, :string,
    values: ~w(thin extralight light normal medium semibold bold extrabold black),
    default: "normal",
    doc: "The text font weight."
  )

  attr(:align, :string,
    values: ~w(start center end justify),
    default: "start",
    doc: "The text alignment."
  )

  attr(:external, :boolean,
    default: false,
    doc:
      "Whether the link leaves the site. Adds a trailing arrow inside the link and the `data-external` hook. It only applies to the link form and does not change where the link opens; set `target` and `rel` when it should open in a new tab."
  )

  attr(:truncate, :boolean,
    default: false,
    doc:
      "Whether the text is truncated to a single line with an ellipsis. The root becomes a block box. `line_clamp` takes precedence."
  )

  attr(:line_clamp, :integer,
    default: nil,
    doc:
      "The number of lines before the text is clamped with an ellipsis. Values `1` to `6` are documented, and any positive integer works. Takes precedence over `truncate`."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include:
      ~w(as href navigate patch replace method csrf_token target rel download hreflang referrerpolicy),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:inner_block, required: true, doc: "The text content.")

  slot(:trailing,
    doc:
      "Inline content rendered after the text, inside the same element. Use it for a decorative indicator such as an external-link arrow."
  )

  def text(assigns) do
    assigns =
      FlintUI.Styled.Color.apply(
        assigns,
        ~w(default highlighted toned muted dimmed inverted neutral info success warning danger primary secondary),
        on_text: "--fl-typography-color"
      )

    external = assigns.external and text_link?(assigns.rest)

    show_external_icon =
      external and is_binary(assigns.external_icon) and assigns.external_icon != ""

    assigns =
      assigns
      |> assign(:external, external)
      |> assign(:show_external_icon, show_external_icon)
      |> assign(
        :rest,
        FlintUI.Styled.Size.put_style(assigns.rest, text_line_clamp_style(assigns.line_clamp))
      )

    ~H"""
    <FlintUI.text
      data-text
      data-typography
      data-size={@size}
      data-color={@data_color}
      data-weight={@weight}
      data-align={@align}
      data-truncate={@truncate and is_nil(@line_clamp)}
      data-line-clamp={@line_clamp}
      data-external={@external}
      class={@class}
      {@rest}
    >
      {render_slot(@inner_block)}
      <:trailing :if={@trailing != [] or @show_external_icon}>
        {render_slot(@trailing)}
        <FlintUI.icon :if={@show_external_icon} name={@external_icon} />
      </:trailing>
    </FlintUI.text>
    """
  end

  defp text_link?(rest), do: not is_nil(rest[:href] || rest[:navigate] || rest[:patch])

  defp text_line_clamp_style(nil), do: nil
  defp text_line_clamp_style(lines), do: "--fl-text-line-clamp: #{lines}"

