defmodule FlintUIDocsWeb.Components do
  use Phoenix.Component

  @moduledoc """
  Generated components for the FlintUI docs site.
  """

  @doc """
  Renders a styled button.

  Generated by `mix flint.add button`. Theming lives in `flint.css`; this wrapper
  maps the `variant`, `color`, and `size` attributes onto the `data-variant`,
  `data-color`, and `data-size` hooks the theme targets. Headless behavior comes
  from `FlintUI.button`.
  """
  attr(:variant, :string,
    values: ~w(solid subtle outline ghost dashed link),
    default: "solid",
    doc: "The visual emphasis of the button."
  )

  attr(:color, :string,
    values: ~w(primary secondary success info warning error neutral),
    default: "neutral",
    doc: "The theme color the variant is built from."
  )

  attr(:size, :string, values: ~w(xs sm md lg xl), default: "md", doc: "The control size.")
  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(disabled loading type),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:inner_block, required: true, doc: "The content of the button.")
  slot(:leading, doc: "Optional content rendered before the label.")
  slot(:trailing, doc: "Optional content rendered after the label.")

  def button(assigns) do
    ~H"""
    <FlintUI.button
      data-button
      data-variant={@variant}
      data-color={@color}
      data-size={@size}
      class={@class}
      {@rest}
    >
      {render_slot(@leading)}
      {render_slot(@inner_block)}
      {render_slot(@trailing)}
    </FlintUI.button>
    """
  end

  @doc """
  Renders a styled collapsible.

  Generated by `mix flint.add collapsible`. Theming lives in `flint.css`; this
  wrapper adds the `data-collapsible` presence hook the reveal transition targets.
  Headless behavior comes from `FlintUI.collapsible`.
  """
  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(id as close_event disabled hidden_until_found open open_event toggle_event),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:content, required: true, doc: "The content to show or hide.")

  slot(:trigger,
    required: true,
    doc: "The trigger. Render a native `<button>` and spread the provided attributes onto it."
  )

  def collapsible(assigns) do
    ~H"""
    <FlintUI.collapsible class={@class} data-collapsible {@rest}>
      <:trigger :let={attrs}>{render_slot(@trigger, attrs)}</:trigger>
      <:content :let={attrs}>{render_slot(@content, attrs)}</:content>
    </FlintUI.collapsible>
    """
  end

  @doc """
  Renders a styled icon.

  Generated by `mix flint.add icon`. Theming lives in `flint.css`; this wrapper
  maps the `size` attribute onto the `data-size` hook the theme targets. Headless
  behavior comes from `FlintUI.icon`.
  """
  attr(:size, :string, values: ~w(sm md lg), default: "md", doc: "The icon size.")
  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(name label),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  def icon(assigns) do
    ~H"""
    <FlintUI.icon
      data-icon
      data-size={@size}
      class={@class}
      {@rest}
    />
    """
  end

  @doc """
  Renders a styled loading indicator.

  Generated by `mix flint.add loading`. Theming lives in `flint.css`; this wrapper
  maps the `variant` and `size` attributes onto the `data-variant` and `data-size`
  hooks the theme targets. Headless behavior comes from `FlintUI.loading`.
  """
  attr(:variant, :string,
    values: ~w(ring ring-bg dots-fade dots-bounce),
    default: "ring",
    doc: "The indicator shape."
  )

  attr(:size, :string, values: ~w(sm md lg), default: "md", doc: "The indicator size.")
  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(duration label variant),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  def loading(assigns) do
    ~H"""
    <FlintUI.loading
      data-loading
      variant={@variant}
      data-size={@size}
      class={@class}
      {@rest}
    />
    """
  end

  @doc """
  Renders a styled toggle.

  Generated by `mix flint.add toggle`. Theming lives in `flint.css`; this wrapper
  maps the `variant`, `color`, and `size` attributes onto the `data-variant`,
  `data-color`, and `data-size` hooks the theme targets. Headless behavior comes
  from `FlintUI.toggle`.
  """
  attr(:variant, :string,
    values: ~w(solid subtle outline ghost dashed),
    default: "solid",
    doc: "How the pressed state is emphasized."
  )

  attr(:color, :string,
    values: ~w(primary secondary success info warning error neutral),
    default: "neutral",
    doc: "The theme color the variant is built from."
  )

  attr(:size, :string, values: ~w(xs sm md lg xl), default: "md", doc: "The control size.")
  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(disabled on_click pressed type),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:inner_block, required: true, doc: "The content of the toggle button.")
  slot(:leading, doc: "Optional content rendered before the label.")
  slot(:trailing, doc: "Optional content rendered after the label.")

  def toggle(assigns) do
    ~H"""
    <FlintUI.toggle
      data-toggle
      data-variant={@variant}
      data-color={@color}
      data-size={@size}
      class={@class}
      {@rest}
    >
      {render_slot(@leading)}
      {render_slot(@inner_block)}
      {render_slot(@trailing)}
    </FlintUI.toggle>
    """
  end

  @doc """
  Renders a styled card.

  Generated by `mix flint.add card`. Theming lives in `flint.css`; this wrapper
  maps the `variant` and `size` attributes onto the `data-variant` and `data-size`
  hooks the theme targets. Headless behavior comes from `FlintUI.card`.
  """
  attr(:variant, :string,
    values: ~w(outline solid subtle),
    default: "outline",
    doc: "The surface treatment of the card."
  )

  attr(:size, :string,
    values: ~w(sm md lg),
    default: "md",
    doc: "The internal spacing of the card."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(as flush),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:inner_block, required: true, doc: "The card body.")
  slot(:action, doc: "Content rendered in the top-right of the header, such as a button.")
  slot(:description, doc: "Supporting text rendered under the title.")
  slot(:footer, doc: "Content rendered in the footer.")
  slot(:header, doc: "Arbitrary content rendered full-width at the bottom of the header.")
  slot(:title, doc: "The card title. Rendered in the header.")

  def card(assigns) do
    ~H"""
    <FlintUI.card
      data-card
      data-variant={@variant}
      data-size={@size}
      class={@class}
      {@rest}
    >
      <:title>{render_slot(@title)}</:title>
      <:description>{render_slot(@description)}</:description>
      <:action>{render_slot(@action)}</:action>
      <:header>{render_slot(@header)}</:header>
      {render_slot(@inner_block)}
      <:footer>{render_slot(@footer)}</:footer>
    </FlintUI.card>
    """
  end
end
