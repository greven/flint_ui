  @doc """
  Renders a styled card.

  Generated by `mix flint.add card`. Theming lives in `flint.css`; this wrapper
  maps the `variant`, `body`, `spacing`, `outline`, `shadow`, and `inverted`
  attributes onto the matching `data-*` hooks the theme targets, and forwards
  `orientation` and `padded` to the headless component. Headless behavior comes
  from `FlintUI.card`.
  """
  attr(:variant, :string,
    values: ~w(solid soft muted ghost),
    default: "solid",
    doc:
      "The neutral surface treatment of the card. `ghost` drops the card's own surface and elevation, composing with `outline` for an outline-only card or a bare container."
  )

  attr(:body, :string,
    values: ~w(seamless inset flush divided separated separated-header separated-footer),
    default: "seamless",
    doc: "How the header, body and footer are set apart."
  )

  attr(:spacing, :string,
    values: ~w(xs sm md lg xl),
    default: "md",
    doc: "The internal spacing of the card."
  )

  attr(:outline, :boolean, default: true, doc: "Draws the card outline.")

  attr(:shadow, :boolean, default: true, doc: "Draws the card's outer elevation.")

  attr(:inverted, :boolean,
    default: false,
    doc: "Inverts the card's surface, text, border and divider colors."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(as orientation padded title_id),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:description, doc: "Supporting text rendered under the title.")

  slot(:footer, doc: "Content rendered at the start of the footer.")

  slot(:footer_actions,
    doc: "Actions rendered at the end of the footer, such as buttons. May be repeated."
  )

  slot(:header,
    doc: "Additional content rendered full-width below the title, description and actions."
  )

  slot(:header_actions,
    doc: "Actions rendered at the end of the header, such as buttons. May be repeated."
  )

  slot(:inner_block,
    doc: "Shorthand for the first body section. Additional sections use `:section`."
  )

  slot(:section, doc: "An additional body section rendered after the implicit first section.")

  slot(:title, doc: "The card title. Rendered in the header.")

  def card(assigns) do
    ~H"""
    <FlintUI.card
      data-card
      data-variant={@variant}
      data-body={@body}
      data-spacing={@spacing}
      data-outline={@outline}
      data-shadow={@shadow}
      data-inverted={@inverted}
      class={@class}
      {@rest}
    >
      <:title>{render_slot(@title)}</:title>
      <:description>{render_slot(@description)}</:description>
      <:header_actions>{render_slot(@header_actions)}</:header_actions>
      <:header>{render_slot(@header)}</:header>
      {render_slot(@inner_block)}
      <:section :for={section <- @section}>
        {render_slot(section)}
      </:section>
      <:footer>{render_slot(@footer)}</:footer>
      <:footer_actions>{render_slot(@footer_actions)}</:footer_actions>
    </FlintUI.card>
    """
  end

