  @doc """
  Renders a styled accordion.

  Generated by `mix flint.add accordion`. Theming lives in `flint.css`; this
  wrapper maps `variant`, `surface`, `indicator_position`, and `transition` onto
  the matching `data-*` hooks and writes the `duration` prop as the reveal
  duration. Headless behavior comes from `FlintUI.accordion`.
  """
  attr(:duration, :integer, default: 200, doc: "Transition duration in milliseconds.")

  attr(:variant, :string,
    values: ~w(simple contained separated),
    default: "simple",
    doc:
      "The layout treatment. `simple` uses dividers only, `contained` wraps the stack in one bordered surface, and `separated` gives every item its own bordered surface."
  )

  attr(:surface, :string,
    values: ~w(solid soft strong ghost),
    default: "solid",
    doc:
      "The neutral surface and edge treatment. `contained` and `separated` paint the surface and outline; `simple` uses the same steps for the divider strength. `ghost` removes the simple divider and the card surface."
  )

  attr(:indicator_position, :string,
    values: ~w(left right),
    default: "right",
    doc: "Which side of the header the indicator sits on."
  )

  attr(:transition, :boolean,
    default: true,
    doc:
      "Whether the panel animates and the default chevron rotates. Set false for an instant toggle."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(id disabled multiple require_open),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:inner_block, required: true, doc: "The accordion items.")

  def accordion(assigns) do
    {rest_style, rest} = Map.pop(assigns.rest, :style)

    duration_style =
      if assigns.duration, do: "--fl-accordion-duration: #{assigns.duration}ms"

    style =
      [duration_style, rest_style]
      |> Enum.reject(&is_nil/1)
      |> Enum.map_join("; ", fn
        value when is_list(value) -> Enum.map_join(value, "; ", &IO.iodata_to_binary/1)
        value -> IO.iodata_to_binary(value)
      end)

    assigns =
      assigns
      |> assign(:rest, rest)
      |> assign(:style, if(style == "", do: nil, else: style))

    ~H"""
    <FlintUI.accordion
      data-accordion
      data-variant={@variant}
      data-surface={@surface}
      data-indicator-position={@indicator_position}
      data-transition={@transition}
      class={@class}
      style={@style}
      {@rest}
    >
      {render_slot(@inner_block)}
    </FlintUI.accordion>
    """
  end

