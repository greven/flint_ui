      "Whether the nested badge's border is dashed. Composes with any variant; variants without a visible border are unaffected."
  )

  attr(:color, :string,
    default: "error",
    doc:
      "The theme color the nested badge is built from, or a raw CSS color such as `#1D72FE` for a one-off accent. Semantic roles: neutral, info, success, warning, error, primary, secondary."
  )

  attr(:size, :string, values: ~w(xs sm md lg xl), default: "xs", doc: "The nested badge size.")

  attr(:position, :string,
    values: ~w(top-right top-left bottom-right bottom-left),
    default: "top-right",
    doc:
      "The anchor corner the badge is placed on. `left` and `right` follow the writing direction."
  )

  attr(:inset, :boolean,
    default: false,
    doc: "Whether the badge sits fully inside the anchor's corner instead of straddling it."
  )

  attr(:ring, :boolean,
    default: false,
    doc: "Adds a ring in the surrounding surface color so the badge reads as a cutout."
  )

  attr(:attention, :string,
    values: ~w(none pulse ping bounce heartbeat),
    default: "none",
    doc:
      "An optional animation that draws attention to the badge. `pulse` fades the badge like Tailwind's `animate-pulse`, `ping` scales a filled halo behind the badge, `bounce` gives the badge a short vertical hop, and `heartbeat` gives it a double scale beat. All stop under `prefers-reduced-motion`."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(as badge_label label status),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:inner_block, required: true, doc: "The anchor the badge is positioned against.")

  def indicator(assigns) do
    assigns =
      FlintUI.Styled.Color.apply(
        assigns,
        ~w(neutral info success warning error primary secondary),
        fill: "--fl-badge-color",
        on_fill: "--fl-badge-color-content",
        on_text: "--fl-badge-text"
      )

    badge_attrs =
      %{
        "data-badge" => true,
        "data-variant" => assigns.variant,
        "data-dashed" => assigns.dashed,
        "data-color" => assigns.data_color,
        "data-size" => assigns.size,
        "data-pill" => true
      }
      |> Enum.reject(fn {_key, value} -> is_nil(value) end)
      |> Map.new()

    {rest_style, rest} = Map.pop(assigns.rest, :style)

    offset_style =
      if assigns.offset not in [nil, 0],
        do: "--fl-indicator-offset: #{assigns.offset}px"

    style =
      [offset_style, rest_style]
      |> Enum.reject(&is_nil/1)
      |> Enum.map_join("; ", fn
        value when is_list(value) -> Enum.map_join(value, "; ", &IO.iodata_to_binary/1)
        value -> IO.iodata_to_binary(value)
      end)

    assigns =
      assigns
      |> assign(:badge_attrs, badge_attrs)
      |> assign(:rest, rest)
      |> assign(:style, if(style == "", do: nil, else: style))

    ~H"""
    <FlintUI.indicator
      data-indicator
      data-position={@position}
      data-inset={@inset}
      data-ring={@ring}
      data-attention={@attention != "none" && @attention}
      class={@class}
      style={@style}
      {@rest}
      badge_attrs={@badge_attrs}
    >
      {render_slot(@inner_block)}
    </FlintUI.indicator>
    """
  end

  @doc """
  Renders a styled avatar.

  Generated by `mix flint.add avatar`. Theming lives in `flint.css`; this wrapper
  maps `size`, `shape`, `radius`, and `color` onto the matching `data-*` hooks,
  with a numeric `size` converted from pixels to rem. Raw and `initials` colors
  are written to the root as CSS inputs. `fallback_icon` supplies the user icon
  when no name is available. Headless behavior comes from `FlintUI.avatar`.
  """
  attr(:fallback_icon, :string,
    default: "lucide-user",
    doc:
      "The Lucide class used when no name is available for initials. Set it to `nil` to render an empty fallback."
  )

  attr(:size, :any,
    default: "md",
    doc:
      "The avatar size, from `xs` to `xl`, or a number of pixels converted to rem (`40` becomes `2.5rem`)."
  )

  attr(:radius, :string,
    values: ~w(none xs sm md lg xl),
    default: "none",
    doc:
      "The corner radius, from `none` for square corners to `xl`, following the shared radius scale. Only applies to `shape=\"square\"`; the default circle stays round."
  )

  attr(:shape, :string,
    values: ~w(circle square),
    default: "circle",
    doc: "The avatar shape. `circle` is the default; `square` uses `radius`."
  )

  attr(:color, :string,
    default: "neutral",
    doc:
      "The fallback fill, a Tailwind palette color such as `tw:rose` (500) or `tw:rose-700`, or a raw CSS color such as `#1D72FE` for a one-off accent. Pass `initials` to derive a stable color from `name`; initials keep a white label unless white falls below 3:1 on that fill. Semantic roles: neutral, info, success, warning, error, primary, secondary."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include:
      ~w(alt name src loading decoding fetchpriority crossorigin referrerpolicy sizes srcset usemap ismap width height),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:fallback,
    doc:
      "Custom fallback content. Takes precedence over initials. The styled wrapper supplies a user icon when `name` is blank."
  )

  def avatar(assigns) do
    color_opts = if assigns.color == "initials", do: [on_fill: :prefer_white], else: []

    assigns =
      assigns
      |> initials_color()
      |> FlintUI.Styled.Color.apply_style(
        ~w(neutral info success warning error primary secondary),
        [fill: "--fl-avatar-color", on_fill: "--fl-avatar-color-content"],
        color_opts
      )

    name = Map.get(assigns.rest, :name)

    root_attrs =
      %{
        "data-avatar" => true,
        "data-size" => scale_size(assigns.size),
        "data-radius" => assigns.radius,
        "data-shape" => assigns.shape,
        "data-color" => assigns.data_color
      }
      |> Enum.reject(fn {_key, value} -> is_nil(value) or value == false end)
      |> Map.new()

    assigns =
      assigns
      |> assign(:avatar_style, avatar_style(assigns))
      |> assign(:root_attrs, root_attrs)
      |> assign(:user_fallback, assigns.fallback != [])
      |> assign(:fallback_icon_visible, blank?(name) and not blank?(assigns.fallback_icon))

    ~H"""
    <FlintUI.avatar
      root_attrs={@root_attrs}
      class={@class}
      root_style={@avatar_style}
      {@rest}
    >
      <:fallback :if={@user_fallback}>{render_slot(@fallback)}</:fallback>
      <:fallback :if={not @user_fallback and @fallback_icon_visible}>
        <FlintUI.icon name={@fallback_icon} />
      </:fallback>
    </FlintUI.avatar>
    """
  end

  defp initials_color(%{color: "initials"} = assigns) do
    color = FlintUI.Styled.Color.initials_color(Map.get(assigns.rest, :name))
    assign(assigns, :color, color)
  end

  defp initials_color(assigns),
    do: assigns

  defp avatar_style(assigns) do
    [assigns.color_style, size_style(assigns.size)]
    |> Enum.reject(&(is_nil(&1) or &1 == ""))
    |> Enum.join("; ")
    |> case do
      "" -> nil
      style -> style
    end
  end

  defp scale_size(size) when size in ~w(xs sm md lg xl),
    do: size

  defp scale_size(_size),
    do: nil

  defp size_style(size) when is_number(size) do
    "--fl-avatar-size: #{Float.to_string(size / 16)}rem"
  end

  defp size_style(size) when is_binary(size) do
    case Float.parse(size) do
      {number, ""} -> "--fl-avatar-size: #{Float.to_string(number / 16)}rem"
      _ -> nil
    end
  end

  defp size_style(_size),
    do: nil

  defp blank?(value) when is_binary(value),
    do: String.trim(value) == ""

  defp blank?(value),
    do: is_nil(value)

