  def toggle(assigns) do
    assigns =
      FlintUI.Styled.Color.apply(
        assigns,
        ~w(neutral info success warning error primary secondary),
        fill: "--fl-toggle-color",
        on_fill: "--fl-toggle-color-content",
        on_text: "--fl-toggle-text"
      )

    assigns =
      if assigns.active_color == "inherit" do
        FlintUI.Styled.Color.clear(assigns, :data_active_color)
      else
        FlintUI.Styled.Color.apply(
          assigns,
          ~w(neutral info success warning error primary secondary),
          [
            fill: "--fl-toggle-active-color",
            on_fill: "--fl-toggle-active-color-content",
            on_text: "--fl-toggle-active-text",
            soft: "--fl-toggle-active-soft",
            soft_border: "--fl-toggle-active-soft-border"
          ],
          prop: :active_color,
          data: :data_active_color
        )
      end

    ~H"""
    <FlintUI.toggle
      data-toggle
      data-variant={@variant}
      data-active-variant={if @active_variant == "inherit", do: @variant, else: @active_variant}
      data-dashed={@dashed}
      data-color={@data_color}
      data-active-color={@data_active_color}
      data-size={@size}
      data-radius={@radius}
      data-pill={@pill}
      data-square={@square}
      data-wide={@wide}
      data-justify={@justify}
      data-depth={@depth}
      data-inset={@inset}
      class={@class}
      {@rest}
    >
      {render_slot(@leading)}
      <FlintUI.icon :if={@icon} name={@icon} />
      <span :if={@on != []} data-part="on-state">{render_slot(@on)}</span>
      <span :if={@off != []} data-part="off-state">{render_slot(@off)}</span>
      {render_slot(@inner_block) || @text}
      {render_slot(@trailing)}
    </FlintUI.toggle>
    """
  end

