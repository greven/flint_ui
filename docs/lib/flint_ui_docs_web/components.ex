  @doc """
  Renders a styled badge.

  Generated by `mix flint.add badge`. Theming lives in `flint.css`; this wrapper
  maps the `variant`, `dashed`, `color`, `size`, `radius`, `pill`, `wide`, and
  `uppercase` attributes onto the matching `data-*` hooks the theme targets, and
  forwards `as`
  or the link attributes to the headless component. `icon` and `text` are content
  shortcuts; the default slot wins over `text`. Headless behavior comes from
  `FlintUI.badge`.
  """

  attr(:icon, :string,
    default: nil,
    doc: "An icon CSS class rendered before the badge's content. The icon is decorative."
  )

  attr(:text, :string,
    default: nil,
    doc:
      "A text label rendered when the default slot is not given. The default slot wins when both are set."
  )

  attr(:variant, :string,
    values: ~w(solid soft subtle surface outline ghost dot),
    default: "subtle",
    doc: "The visual emphasis of the badge."
  )

  attr(:dashed, :boolean,
    default: false,
    doc:
      "Whether the badge's border is dashed. Composes with any variant; variants without a visible border are unaffected."
  )

  attr(:color, :string,
    default: "neutral",
    doc:
      "The theme color the variant is built from, or a raw CSS color such as `#1D72FE` for a one-off accent. Semantic roles: neutral, info, success, warning, error, primary, secondary."
  )

  attr(:size, :string, values: ~w(xs sm md lg xl), default: "md", doc: "The badge size.")

  attr(:radius, :string,
    values: ~w(none xs sm md lg xl),
    default: "md",
    doc:
      "The corner radius, from `none` for square corners to `xl`, following the shared radius scale. Use `pill` for a full-radius pill."
  )

  attr(:pill, :boolean,
    default: false,
    doc:
      "Whether the badge renders as a full-radius pill. Pills also add inline padding so a short label clears the curve, and `pill` takes precedence over `radius`."
  )

  attr(:wide, :boolean,
    default: false,
    doc: "Whether the badge fills the width of its container."
  )

  attr(:uppercase, :boolean,
    default: false,
    doc: "Whether the badge text is rendered in uppercase."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include:
      ~w(as href navigate patch replace method csrf_token target rel download hreflang referrerpolicy),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:inner_block, doc: "The content of the badge.")

  slot(:leading,
    doc:
      "Optional content rendered before the badge's content. A nested Button or Toggle is sized to the badge's row."
  )

  slot(:trailing,
    doc:
      "Optional content rendered after the badge's content. A nested Button or Toggle is sized to the badge's row and inset from the edge."
  )

  def badge(assigns) do
    assigns =
      FlintUI.Styled.Color.apply(
        assigns,
        ~w(neutral info success warning error primary secondary),
        fill: "--fl-badge-color",
        on_fill: "--fl-badge-color-content",
        on_text: "--fl-badge-text"
      )

    ~H"""
    <FlintUI.badge
      data-badge
      data-leading={@leading != []}
      data-trailing={@trailing != []}
      data-variant={@variant}
      data-dashed={@dashed}
      data-color={@data_color}
      data-size={@size}
      data-radius={@radius}
      data-pill={@pill}
      data-wide={@wide}
      data-uppercase={@uppercase}
      class={@class}
      {@rest}
    >
      {render_slot(@leading)}
      <FlintUI.icon :if={@icon} name={@icon} />
      {render_slot(@inner_block) || @text}
      {render_slot(@trailing)}
    </FlintUI.badge>
    """
  end

