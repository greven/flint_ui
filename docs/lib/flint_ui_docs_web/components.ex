  """
  attr(:size, :any,
    default: "md",
    doc:
      "The flag width, from `xs` to `xl`, or a number of pixels converted to rem (`40` becomes `2.5rem`). Height follows the flag's aspect ratio: 4:3 for `regular`, 1:1 for `square` and `round`."
  )

  attr(:radius, :string,
    values: ~w(none xs sm md lg xl full),
    default: "xs",
    doc: "The corner radius from the shared radius scale. `round` always uses a full radius."
  )

  attr(:overlay, :string,
    values: ~w(none linear wave),
    default: "none",
    doc: "An optional decorative overlay across the flag."
  )

  attr(:border, :boolean,
    default: false,
    doc: "Adds a subtle inset border. Useful on light flags and photo surfaces."
  )

  attr(:shadow, :boolean,
    default: false,
    doc: "Adds the shared small elevation shadow."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(code label path shape),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  def flag(assigns) do
    assigns =
      assigns
      |> assign(:data_size, FlintUI.Styled.Size.scale(assigns.size))
      |> assign(
        :rest,
        FlintUI.Styled.Size.put_style(
          assigns.rest,
          FlintUI.Styled.Size.style(assigns.size, "--fl-flag-size")
        )
      )

    ~H"""
    <FlintUI.flag
      data-flag
      data-size={@data_size}
      data-radius={@radius}
      data-overlay={@overlay}
      data-border={@border}
      data-shadow={@shadow}
      class={@class}
      {@rest}
    />
    """
  end

