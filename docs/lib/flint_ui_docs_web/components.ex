defmodule FlintUIDocsWeb.Components do
  use Phoenix.Component

  @moduledoc """
  Generated components for the FlintUI docs site.
  """

  @doc """
  Renders a styled button.

  Generated by `mix flint.add button`. Theming lives in `flint.css`; this wrapper
  maps the `variant`, `color`, `size`, `square`, `wide`, `depth`, and `inset`
  attributes onto the `data-variant`, `data-color`, `data-size`, `data-square`,
  `data-wide`, `data-depth`, and `data-inset` hooks the theme targets. Headless
  behavior comes from `FlintUI.button`.
  """

  attr(:variant, :string,
    values: ~w(solid soft subtle outline dashed ghost link),
    default: "outline",
    doc: "The visual emphasis of the button."
  )

  attr(:color, :string,
    values: ~w(primary secondary success info warning error neutral),
    default: "neutral",
    doc: "The theme color the variant is built from."
  )

  attr(:size, :string, values: ~w(xs sm md lg xl), default: "md", doc: "The control size.")

  attr(:square, :boolean,
    default: false,
    doc:
      "Whether the button is square. Use it for icon-only buttons; the width follows the selected size."
  )

  attr(:wide, :boolean,
    default: false,
    doc: "Whether the button fills the width of its container."
  )

  attr(:depth, :boolean,
    default: true,
    doc:
      "Whether solid and outline buttons show their highlight/inner line. Shadows are always on for solid, subtle, and outline; remove them with `--fl-control-shadow`."
  )

  attr(:inset, :boolean,
    default: false,
    doc:
      "Whether to negate the button's invisible padding so its content aligns with surrounding content. Most useful on ghost and link variants; the hit area is unchanged."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include:
      ~w(disabled loading type href navigate patch replace method csrf_token target rel download hreflang referrerpolicy name value form formaction formenctype formmethod formnovalidate formtarget popovertarget autofocus command commandfor),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:inner_block, required: true, doc: "The content of the button.")
  slot(:leading, doc: "Optional content rendered before the button's content.")
  slot(:trailing, doc: "Optional content rendered after the button's content.")

  def button(assigns) do
    ~H"""
    <FlintUI.button
      data-button
      data-variant={@variant}
      data-color={@color}
      data-size={@size}
      data-square={@square}
      data-wide={@wide}
      data-depth={@depth}
      data-inset={@inset}
      class={@class}
      {@rest}
    >
      {render_slot(@leading)}
      {render_slot(@inner_block)}
      {render_slot(@trailing)}
    </FlintUI.button>
    """
  end

  @doc """
  Renders a styled collapsible.

  Generated by `mix flint.add collapsible`. Theming lives in `flint.css`; this
  wrapper adds the `data-collapsible` presence hook the reveal transition targets.
  Headless behavior comes from `FlintUI.collapsible`.
  """
  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(id as close_event disabled hidden_until_found open open_event toggle_event),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:content, required: true, doc: "The content to show or hide.")

  slot(:trigger,
    required: true,
    doc: "The trigger. Render a native `<button>` and spread the provided attributes onto it."
  )

  def collapsible(assigns) do
    ~H"""
    <FlintUI.collapsible class={@class} data-collapsible {@rest}>
      <:trigger :let={attrs}>{render_slot(@trigger, attrs)}</:trigger>
      <:content :let={attrs}>{render_slot(@content, attrs)}</:content>
    </FlintUI.collapsible>
    """
  end

  @doc """
  Renders a styled icon.

  Generated by `mix flint.add icon`. Theming lives in `flint.css`; this wrapper
  maps the `size` attribute onto the `data-size` hook the theme targets. Headless
  behavior comes from `FlintUI.icon`.
  """
  attr(:size, :string, values: ~w(sm md lg), default: "md", doc: "The icon size.")
  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(name label),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  def icon(assigns) do
    ~H"""
    <FlintUI.icon
      data-icon
      data-size={@size}
      class={@class}
      {@rest}
    />
    """
  end

  @doc """
  Renders a styled loading indicator.

  Generated by `mix flint.add loading`. Theming lives in `flint.css`; this wrapper
  maps the `variant`, `color`, and `size` attributes onto the `data-variant`,
  `data-color`, and `data-size` hooks the theme targets. Headless behavior comes
  from `FlintUI.loading`.
  """
  attr(:variant, :string,
    values: ~w(ring ring-bg ring-dash dots-fade dots-bounce bars-scale infinity),
    default: "ring",
    doc: "The indicator shape."
  )

  attr(:color, :string,
    values: ~w(inherit primary secondary success info warning error neutral),
    default: "inherit",
    doc: "The theme color of the indicator. `inherit` follows the surrounding `currentColor`."
  )

  attr(:size, :string, values: ~w(sm md lg), default: "md", doc: "The indicator size.")
  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(duration label variant weight),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  def loading(assigns) do
    ~H"""
    <FlintUI.loading
      data-loading
      variant={@variant}
      data-color={@color}
      data-size={@size}
      class={@class}
      {@rest}
    />
    """
  end

  @doc """
  Renders text with a loading animation.

  Generated by `mix flint.add loading_text`. Theming lives in `flint.css`; this
  wrapper maps the `variant` and `color` attributes onto the `data-variant` and
  `data-color` hooks the theme targets. Headless behavior comes from
  `FlintUI.loading_text`.
  """
  attr(:variant, :string,
    values: ~w(dots blink shimmer wave),
    default: "dots",
    doc: "The text loading animation."
  )

  attr(:color, :string,
    values: ~w(inherit primary secondary success info warning error neutral),
    default: "inherit",
    doc: "The theme color of the text. `inherit` follows the surrounding `currentColor`."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(text dots duration variant),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  def loading_text(assigns) do
    ~H"""
    <FlintUI.loading_text
      data-loading_text
      variant={@variant}
      data-color={@color}
      class={@class}
      {@rest}
    />
    """
  end

  @doc """
  Renders a styled toggle.

  Generated by `mix flint.add toggle`. Theming lives in `flint.css`; this wrapper
  maps the `variant`, `color`, and `size` attributes onto the `data-variant`,
  `data-color`, and `data-size` hooks the theme targets. Headless behavior comes
  from `FlintUI.toggle`.
  """
  attr(:variant, :string,
    values: ~w(solid subtle outline ghost dashed),
    default: "solid",
    doc: "How the pressed state is emphasized."
  )

  attr(:color, :string,
    values: ~w(primary secondary success info warning error neutral),
    default: "neutral",
    doc: "The theme color the variant is built from."
  )

  attr(:size, :string, values: ~w(xs sm md lg xl), default: "md", doc: "The control size.")
  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(disabled on_click pressed type),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:inner_block, required: true, doc: "The content of the toggle button.")
  slot(:leading, doc: "Optional content rendered before the toggle's content.")
  slot(:trailing, doc: "Optional content rendered after the toggle's content.")

  def toggle(assigns) do
    ~H"""
    <FlintUI.toggle
      data-toggle
      data-variant={@variant}
      data-color={@color}
      data-size={@size}
      class={@class}
      {@rest}
    >
      {render_slot(@leading)}
      {render_slot(@inner_block)}
      {render_slot(@trailing)}
    </FlintUI.toggle>
    """
  end

  @doc """
  Renders a styled card.

  Generated by `mix flint.add card`. Theming lives in `flint.css`; this wrapper
  maps the `variant`, `body`, `spacing`, `outline`, `shadow`, and `inverted`
  attributes onto the matching `data-*` hooks the theme targets, and forwards
  `orientation` and `padded` to the headless component. Headless behavior comes
  from `FlintUI.card`.
  """
  attr(:variant, :string,
    values: ~w(solid soft muted ghost),
    default: "solid",
    doc:
      "The neutral surface treatment of the card. `ghost` drops the card's own surface and elevation, composing with `outline` for an outline-only card or a bare container."
  )

  attr(:body, :string,
    values: ~w(seamless inset flush divided separated separated-header separated-footer),
    default: "seamless",
    doc: "How the header, body and footer are set apart."
  )

  attr(:spacing, :string,
    values: ~w(xs sm md lg xl),
    default: "md",
    doc: "The internal spacing of the card."
  )

  attr(:outline, :boolean, default: true, doc: "Draws the card outline.")

  attr(:shadow, :boolean, default: true, doc: "Draws the card's outer elevation.")

  attr(:inverted, :boolean,
    default: false,
    doc: "Inverts the card's surface, text, border and divider colors."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(as orientation padded title_id),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:description, doc: "Supporting text rendered under the title.")

  slot(:footer, doc: "Content rendered at the start of the footer.")

  slot(:footer_actions,
    doc: "Actions rendered at the end of the footer, such as buttons. May be repeated."
  )

  slot(:header,
    doc: "Additional content rendered full-width below the title, description and actions."
  )

  slot(:header_actions,
    doc: "Actions rendered at the end of the header, such as buttons. May be repeated."
  )

  slot(:inner_block,
    doc: "Shorthand for the first body section. Additional sections use `:section`."
  )

  slot(:section, doc: "An additional body section rendered after the implicit first section.")

  slot(:title, doc: "The card title. Rendered in the header.")

  def card(assigns) do
    ~H"""
    <FlintUI.card
      data-card
      data-variant={@variant}
      data-body={@body}
      data-spacing={@spacing}
      data-outline={@outline}
      data-shadow={@shadow}
      data-inverted={@inverted}
      class={@class}
      {@rest}
    >
      <:title>{render_slot(@title)}</:title>
      <:description>{render_slot(@description)}</:description>
      <:header_actions>{render_slot(@header_actions)}</:header_actions>
      <:header>{render_slot(@header)}</:header>
      {render_slot(@inner_block)}
      <:section :for={section <- @section}>
        {render_slot(section)}
      </:section>
      <:footer>{render_slot(@footer)}</:footer>
      <:footer_actions>{render_slot(@footer_actions)}</:footer_actions>
    </FlintUI.card>
    """
  end

  @doc """
  Renders a styled group.

  Generated by `mix flint.add group`. Theming lives in `flint.css`; this wrapper
  maps the `variant` and `size` attributes onto the `data-variant` and `data-size`
  hooks the theme targets. Headless structure comes from `FlintUI.group`.
  """
  attr(:variant, :string,
    values: ~w(attached framed),
    default: "attached",
    doc:
      "How the children are joined. `attached` collapses their seams into one block; `framed` wraps them in a padded, bordered shell."
  )

  attr(:size, :string,
    values: ~w(xs sm md lg xl),
    default: "md",
    doc: "The group spacing, cascaded onto the child controls."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(as label orientation),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:inner_block, required: true, doc: "The grouped children.")

  def group(assigns) do
    ~H"""
    <FlintUI.group
      data-group
      data-variant={@variant}
      data-size={@size}
      class={@class}
      {@rest}
    >
      {render_slot(@inner_block)}
    </FlintUI.group>
    """
  end
end
