  @doc """
  Renders a styled alert.

  Generated by `mix flint.add alert`. Theming lives in `flint.css`; this wrapper
  maps the `variant`, `color`, `spacing`, `shadow`, `border`, and `background`
  attributes onto the matching `data-*` hooks the theme targets, and forwards the headless
  attributes, including `intent`, `title`, `orientation`, and `show_close`.
  `show_icon` keeps the intent color while hiding its default icon; an explicit
  `:icon` slot always renders. Headless behavior comes from `FlintUI.alert`.
  """
  attr(:show_icon, :boolean,
    default: true,
    doc:
      "Whether to render the default icon selected by `intent`. An explicit `:icon` slot always renders."
  )

  attr(:variant, :string,
    values: ~w(solid soft outline),
    default: "outline",
    doc:
      "The visual emphasis of the alert. `outline` is the default tinted surface with the role's full-strength edge, `soft` keeps the tint with the faint matching edge, and `solid` fills the alert with the role color."
  )

  attr(:color, :string,
    default: nil,
    doc:
      "The theme color the variant is built from, a palette hue such as `pink` or `cyan`, or a raw CSS color such as `#1D72FE` for a one-off accent. Defaults to the `intent` when set, otherwise `neutral`. Semantic roles: neutral, info, success, warning, danger, primary, secondary."
  )

  attr(:spacing, :string,
    values: ~w(xs sm md lg xl),
    default: "md",
    doc: "The internal spacing of the alert."
  )

  attr(:shadow, :boolean, default: true, doc: "Draws the alert's outer elevation.")

  attr(:border, :string,
    values: ~w(solid dashed none),
    default: "solid",
    doc:
      "The edge treatment. `solid` is the default, `dashed` keeps the variant's color with a dashed stroke, and `none` removes the edge while keeping the variant's surface."
  )

  attr(:background, :boolean,
    default: true,
    doc:
      "Whether the alert paints its surface. Set false to keep the border and elevation over a transparent background; the label falls back to the role text."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include: ~w(as close_event close_label id intent orientation role show_close title),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:actions,
    doc:
      "Actions rendered below the body, or beside it with `orientation=\"horizontal\"`. May be repeated."
  )

  slot(:close,
    doc:
      "Content for the close button. The styled wrapper supplies a close icon; the unstyled base falls back to a multiplication glyph."
  )

  slot(:icon,
    doc:
      "An icon rendered before the content. It replaces the default intent icon; the styled wrapper supplies one from the intent when this slot is absent."
  )

  slot(:inner_block, doc: "The body of the alert.")

  def alert(assigns) do
    intent = Map.get(assigns.rest, :intent)
    assigns = assign(assigns, :color, assigns.color || intent || "neutral")

    assigns =
      FlintUI.Styled.Color.apply(
        assigns,
        ~w(neutral info success warning danger primary secondary),
        fill: "--fl-alert-color",
        on_fill: "--fl-alert-color-content",
        on_text: "--fl-alert-text"
      )

    # `intent_icon/1` picks these at runtime, so Tailwind cannot discover them by
    # scanning the wrapper. Keep the class names literal for the scanner:
    # lucide-info lucide-circle-check lucide-circle-exclamation-point lucide-circle-x
    intent_icon =
      if assigns.icon == [] and assigns.show_icon do
        FlintUI.Base.Alert.intent_icon(intent)
      end

    assigns = assign(assigns, :intent_icon, intent_icon)

    ~H"""
    <FlintUI.alert
      data-alert
      data-variant={@variant}
      data-color={@data_color}
      data-spacing={@spacing}
      data-shadow={@shadow}
      data-border={@border}
      data-background={@background}
      class={@class}
      {@rest}
    >
      <:icon :if={@icon != []}>{render_slot(@icon)}</:icon>
      <:icon :if={@intent_icon}>
        <FlintUI.icon name={@intent_icon} />
      </:icon>
      <:actions>{render_slot(@actions)}</:actions>
      <:close>
        {render_slot(@close)}
        <FlintUI.icon :if={@close == []} name="lucide-x" />
      </:close>
      {render_slot(@inner_block)}
    </FlintUI.alert>
    """
  end

