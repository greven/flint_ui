  @doc """
  Renders a styled tabs component.

  Generated by `mix flint.add tabs`. Theming lives in `flint.css`; this wrapper
  maps the `variant`, `color`, and `size` attributes onto the `data-variant`,
  `data-color`, and `data-size` hooks the theme targets. Headless behavior comes
  from `FlintUI.tabs`.
  """
  attr(:variant, :string,
    values: ~w(outlined segmented minimal),
    default: "outlined",
    doc: "The visual treatment of the tab list."
  )

  attr(:color, :string,
    default: "neutral",
    doc:
      "The theme color the active state is built from, or a raw CSS color such as `#1D72FE` for a one-off accent. Semantic roles: primary, secondary, success, info, warning, error, neutral."
  )

  attr(:size, :string,
    values: ~w(xs sm md lg xl),
    default: "md",
    doc: "The control size of the default triggers."
  )

  attr(:grow, :boolean,
    default: false,
    doc:
      "Whether the tabs share the available width. Horizontal only. Ignored when `scrollable` or `fadable` is set."
  )

  attr(:align, :string,
    values: ~w(start center end spaced),
    default: "start",
    doc:
      "Where the tabs sit in a horizontal tab list. `spaced` uses space-between. Ignored when `grow` fills the row."
  )

  attr(:gap, :string,
    values: ~w(auto sm md lg xl),
    default: "auto",
    doc:
      "The distance between triggers. `auto` follows the variant; raise it for composed triggers such as buttons, which bring their own padding and border."
  )

  attr(:class, :any, default: nil, doc: "Additional classes appended to the generated component.")

  attr(:rest, :global,
    include:
      ~w(id activation_mode change_event disabled fadable findable label loop orientation scrollable value),
    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  slot(:tab,
    required: true,
    doc:
      "One tab. Render the label as the slot content, or set `custom` and render the trigger yourself with the provided attributes."
  ) do
    attr(:value, :string,
      required: true,
      doc: "The tab value. Used in the tab and panel ids, so use a slug."
    )

    attr(:disabled, :boolean, doc: "Whether the tab is disabled. Defaults to `false`.")

    attr(:custom, :boolean,
      doc:
        "Whether the slot renders the trigger. The slot receives the trigger attributes through `:let`. Defaults to `false`. A raw custom button should set `type=\"button\"`."
    )

    attr(:aria_label, :string,
      doc:
        "An accessible name for the trigger, applied as `aria-label`. Useful for icon-only tabs."
    )

    attr(:class, :any,
      doc:
        "Additional classes for a default trigger. A custom trigger is styled by the element you render."
    )
  end

  slot(:panel, doc: "A panel. Match its value to a tab value.") do
    attr(:value, :string, required: true, doc: "The value of the tab this panel belongs to.")

    attr(:focusable, :boolean,
      doc: "Whether the panel receives `tabindex=\"0\"`. Defaults to `true`."
    )

    attr(:class, :any, doc: "Additional classes for the panel.")
  end

  def tabs(assigns) do
    assigns =
      FlintUI.Styled.Color.apply(
        assigns,
        ~w(primary secondary success info warning error neutral),
        fill: "--fl-tabs-color",
        on_page: "--fl-tabs-text"
      )

    ~H"""
    <FlintUI.tabs
      data-tabs
      data-variant={@variant}
      data-color={@data_color}
      data-size={@size}
      data-grow={@grow}
      data-align={@align}
      data-gap={@gap}
      class={@class}
      {@rest}
    >
      <:tab
        :let={attrs}
        :for={tab <- @tab}
        value={tab.value}
        disabled={Map.get(tab, :disabled, false)}
        custom={Map.get(tab, :custom, false)}
        aria_label={Map.get(tab, :aria_label)}
        class={Map.get(tab, :class)}
      >
        {render_slot(tab, attrs)}
      </:tab>
      <:panel
        :for={panel <- @panel}
        value={panel.value}
        focusable={Map.get(panel, :focusable, true)}
        class={Map.get(panel, :class)}
      >
        {render_slot(panel)}
      </:panel>
    </FlintUI.tabs>
    """
  end
end
