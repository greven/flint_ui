        "data-progress_group" => true,
        "data-size" => assigns.size,
        "data-color" => assigns.data_color,
        "data-radius" => assigns.radius,
        "style" => style
      }
      |> Enum.reject(fn {_key, value} -> is_nil(value) or value == false or value == "" end)
      |> Map.new()

    segments = Enum.map(assigns.segment, &segment_assigns/1)

    assigns =
      assigns
      |> assign(:root_attrs, root_attrs)
      |> assign(:rest, rest)
      |> assign(:segments, segments)

    ~H"""
    <FlintUI.progress_group
      root_attrs={@root_attrs}
      class={@class}
      {@rest}
    >
      <:status :if={@status != []}>{render_slot(@status)}</:status>
      <:segment
        :for={segment <- @segments}
        :if={Map.get(segment, :inner_block)}
        value={segment.value}
        label={Map.get(segment, :label)}
        icon={Map.get(segment, :icon)}
        color={segment.data_color}
        style={segment.color_style}
        class={Map.get(segment, :class)}
      >
        {render_slot(segment)}
      </:segment>
      <:segment
        :for={segment <- @segments}
        :if={!Map.get(segment, :inner_block)}
        value={segment.value}
        label={Map.get(segment, :label)}
        icon={Map.get(segment, :icon)}
        color={segment.data_color}
        style={segment.color_style}
        class={Map.get(segment, :class)}
      />
    </FlintUI.progress_group>
    """
  end

  defp segment_assigns(segment) do
    {data_color, color_style} =
      case Map.get(segment, :color) do
        nil ->
          {nil, nil}

        color ->
          {data_color, color_style} =
            FlintUI.Styled.Color.resolve_style(
              color,
              ~w(neutral info success warning error primary secondary),
              fill: "--fl-progress-group-color"
            )

          {data_color, color_style}
      end

    style =
      [Map.get(segment, :style), color_style]
      |> Enum.reject(&(&1 in [nil, ""]))
      |> Enum.join("; ")

    segment
    |> Map.put(:data_color, data_color)
    |> Map.put(:color_style, if(style == "", do: nil, else: style))
  end
end
