    doc: "Additional HTML attributes, forwarded to the headless component."
  )

  def textarea(assigns) do
    # Autogrow writes its row limits to the public CSS inputs, keeping every
    # numeric value in one inline style that composes with a caller's `style`.
    min_rows = if is_integer(assigns.min_rows), do: max(assigns.min_rows, 1), else: 2
    max_rows = if is_integer(assigns.max_rows), do: max(assigns.max_rows, min_rows), else: 8

    {rest_style, rest} = Map.pop(assigns.rest, :style)

    autogrow_style =
      if assigns.autogrow do
        "--fl-textarea-min-rows: #{min_rows}; --fl-textarea-max-rows: #{max_rows}"
      end

    style =
      [autogrow_style, rest_style]
      |> Enum.reject(&(&1 in [nil, ""]))
      |> Enum.join("; ")

    # Without `field-sizing`, the control keeps the native rows height. Use the
    # minimum rows as that fallback, unless the caller set `rows` explicitly.
    rest =
      if assigns.autogrow and is_nil(Map.get(rest, :rows)) do
        Map.put(rest, :rows, min_rows)
      else
        rest
      end

    rest = if style == "", do: rest, else: Map.put(rest, :style, style)

    root_attrs =
      %{
        "data-textarea" => true,
        "data-field" => true,
        "data-size" => assigns.size,
        "data-radius" => assigns.radius,
        "data-resize" => assigns.resize,
        "data-autogrow" => assigns.autogrow
      }
      |> Enum.reject(fn {_key, value} -> is_nil(value) or value == false end)
      |> Map.new()

    assigns =
      assigns
      |> assign(:root_attrs, root_attrs)
      |> assign(:rest, rest)

    ~H"""
    <FlintUI.textarea root_attrs={@root_attrs} class={@class} {@rest} />
    """
  end

