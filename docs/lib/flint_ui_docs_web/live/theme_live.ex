  defp token_groups do
    FlintUI.Generator.theme_source()
    |> then(&Regex.scan(~r/--fl-[a-z0-9-]+/, &1))
    |> List.flatten()
    |> Enum.uniq()
    |> Enum.sort()
    |> Enum.group_by(fn token ->
      token |> String.replace_prefix("--fl-", "") |> String.split("-") |> hd()
    end)
    |> Enum.sort_by(fn {namespace, _} -> namespace end)
  end
