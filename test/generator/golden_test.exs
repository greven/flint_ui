defmodule FlintUI.Generator.GoldenTest do
  @moduledoc """
  Keeps the docs site's generated components in sync with the generator.

  `docs/lib/flint_ui_docs_web/components.ex` is generated by `mix flint.add`
  and refreshed by `mix flint.update`, so it doubles as a golden copy of every
  wrapper. When a template or an entry changes, this test fails until the docs
  are regenerated in the same change.
  """

  use ExUnit.Case, async: true

  alias FlintUI.{Generator, Styled}

  @docs_components Path.expand("../../docs/lib/flint_ui_docs_web/components.ex", __DIR__)

  test "the docs components match the generated wrappers" do
    if File.exists?(@docs_components) do
      content = File.read!(@docs_components)
      lines = String.split(content, "\n")

      blocks =
        content
        |> Generator.blocks()
        |> Map.new(&{&1.name, Generator.block_body(lines, &1)})

      for name <- Styled.names() do
        key = to_string(name)

        assert body = Map.get(blocks, key),
               """
               The docs site has no generated #{name} wrapper. Run
               `cd docs && mix flint.add #{name}`.
               """

        assert canonical(body) == canonical(Generator.component_body(name)),
               """
               The generated #{name} wrapper in
               docs/lib/flint_ui_docs_web/components.ex is stale.

               Run `cd docs && mix flint.update --force`.
               """
      end
    else
      :ok
    end
  end

  # The host formatter rewraps calls, drops redundant brackets, and reorders
  # HEEx attributes, so compare the token content instead of the text. Adding,
  # removing, or changing any token still fails; pure reformatting does not.
  defp canonical(body) do
    body
    |> String.replace(~r/[\[\](){}]/, " ")
    |> then(&Regex.scan(~r/[^\s]+/, &1))
    |> List.flatten()
    |> Enum.sort()
  end
end
