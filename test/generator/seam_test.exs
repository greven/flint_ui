defmodule FlintUI.Generator.SeamTest do
  @moduledoc """
  Freezes the runtime API that generated wrappers call.

  Generated wrappers live in the host application as source, so the functions
  they call are public API across library releases. This test fails when a
  template starts calling something new, or when one of the seam functions is
  renamed or removed. Both changes require a deliberate
  `FlintUI.Generator.wrapper_api/0` bump and a `mix flint.update` path.
  """

  use ExUnit.Case, async: true

  alias FlintUI.{Generator, Styled}

  # Functions generated wrappers may call at runtime. Add here only when a new
  # wrapper genuinely needs a shared helper; prefer an existing entry.
  @seam [
    {FlintUI.Styled.Color, :apply},
    {FlintUI.Styled.Color, :apply_style},
    {FlintUI.Styled.Color, :clear},
    {FlintUI.Styled.Color, :initials_color},
    {FlintUI.Styled.Color, :resolve_style},
    {FlintUI.Styled.ContainerSize, :resolve},
    {FlintUI.Styled.Size, :put_style},
    {FlintUI.Styled.Size, :scale},
    {FlintUI.Styled.Size, :style}
  ]

  @deep_call ~r/\b(FlintUI(?:\.[A-Z]\w*)+)\.([a-z_]\w*[?!]?)\b/
  @root_call ~r/\bFlintUI\.([a-z_]\w*[?!]?)\b/

  test "generated wrappers call only the frozen runtime seam" do
    found =
      Styled.names()
      |> Enum.flat_map(&deep_calls(Generator.component_source(&1)))
      |> Enum.uniq()
      |> Enum.sort()

    assert found == Enum.sort(@seam), """
    The generated-code runtime seam changed.

    Wrappers generated by an earlier version call these functions in the host
    application, so their names and signatures are public API. If the change is
    intentional, add the call to @seam and bump
    `FlintUI.Generator.wrapper_api/0`. Otherwise use a base component or an
    existing seam function.

    Found:   #{inspect(found)}
    Allowed: #{inspect(Enum.sort(@seam))}
    """

    for {module, function} <- found do
      assert Code.ensure_loaded?(module), "seam module #{inspect(module)} does not exist"

      assert Enum.any?(module.__info__(:functions), fn {exported, _arity} ->
               exported == function
             end),
             "seam function #{inspect(module)}.#{function} does not exist"
    end
  end

  test "generated wrappers call only registered base components" do
    components = FlintUI.components()

    for name <- Styled.names(),
        function <- root_calls(Generator.component_source(name)) do
      assert function in components, """
      The generated #{name} wrapper calls `FlintUI.#{function}`, which is not a
      registered base component. Generated code may only call base components
      and the frozen seam; see `test/generator/seam_test.exs`.
      """
    end
  end

  defp deep_calls(source) do
    @deep_call
    |> Regex.scan(source, capture: :all_but_first)
    |> Enum.map(fn [module, function] ->
      {Module.concat([module]), String.to_atom(function)}
    end)
  end

  defp root_calls(source) do
    @root_call
    |> Regex.scan(source, capture: :all_but_first)
    |> Enum.map(fn [function] -> String.to_atom(function) end)
  end
end
