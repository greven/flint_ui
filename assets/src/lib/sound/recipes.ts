function bell(f: number, peak: number, decay: number, send: number): Spec {
  // A struck bar: fundamental plus inharmonic partials.
  const partials: Array<[ratio: number, gain: number]> = [
    [1, 1],
    [2.76, 0.42],
    [5.4, 0.18],
    [8.93, 0.07],
  ];

  return partials.map(([ratio, gain], i): ToneLayer => ({
    kind: "tone",
    at: 0,
    wave: "sine",
    f: f * ratio,
    f2: null,
    glide: 0.06,
    a: 0.002,
    d: decay * (1 - i * 0.16),
    peak: peak * gain,
    send,
  }));
}

