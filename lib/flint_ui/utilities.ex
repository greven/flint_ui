  defp responsive_description do
    desc("""
    Breakpoint-prefixed display toggles. The layout primitives already adapt on
    their own; these cover the "hidden on small screens" cases.
    """)
  end

  defp responsive_utilities do
    display_names = [
      {"block", "display: block"},
      {"inline-block", "display: inline-block"},
      {"inline", "display: inline"},
      {"flex", "display: flex"},
      {"inline-flex", "display: inline-flex"},
      {"hidden", "display: none"},
      {"contents", "display: contents"},
      {"flow-root", "display: flow-root"}
    ]

    for {breakpoint, _width} <- @breakpoints,
        {name, declaration} <- display_names do
      util("fl-#{breakpoint}-#{name}", declaration)
    end
  end

  defp responsive_css do
    Enum.map_join(@breakpoints, "\n\n", fn {breakpoint, width} ->
      rules =
        for {name, declaration} <- [
              {"block", "display: block"},
              {"inline-block", "display: inline-block"},
              {"inline", "display: inline"},
              {"flex", "display: flex"},
              {"inline-flex", "display: inline-flex"},
              {"hidden", "display: none"},
              {"contents", "display: contents"},
              {"flow-root", "display: flow-root"}
            ] do
          "    .fl-#{breakpoint}-#{name} { #{declaration}; }"
        end

      """
        @media (min-width: #{width}) {
      #{Enum.join(rules, "\n")}
        }
      """
      |> String.trim_trailing()
    end)
  end
