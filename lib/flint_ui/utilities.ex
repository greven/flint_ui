  defp container_utilities do
    base =
      "inline-size: 100%; margin-inline: auto; padding-inline: var(--fl-spacing-lg);"

    [
      util("fl-container", base <> " responsive max-inline-size at each breakpoint"),
      util("fl-container-fluid", base <> " max-inline-size: none")
      | Enum.map(@container_sizes, fn size ->
          util(
            "fl-container-#{size}",
