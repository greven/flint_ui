        "\n",
        fn {width, size} ->
          """
            @media (min-width: #{width}) {
              .fl-container { max-inline-size: var(--fl-container-#{size}); }
            }
          """
          |> String.trim_trailing()
        end
      )

    [String.trim_trailing(base), sizes, media]
    |> Enum.reject(&(&1 == ""))
    |> Enum.join("\n\n")
  end

