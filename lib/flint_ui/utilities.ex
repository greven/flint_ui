defmodule FlintUI.Utilities do
  @moduledoc """
  The CSS utility layer.

  FlintUI ships a small, fixed set of utility classes for layout, spacing, and
  theme-aware styling. The classes are prefixed with `fl-` and read the same
  `--fl-*` tokens as the components, so they follow the active theme, palette,
  and color scheme.

  The layer is generated, not hand-written. `mix flint.utilities` writes
  `assets/css/flint-utilities.css`; `mix flint.setup` and `mix flint.theme`
  install or refresh it by default. Put overrides after the import, or pass
  `--no-utilities` to setup/theme to leave the layer out.

  There is no JIT and no arbitrary-value syntax. Every class in this module is
  emitted into the generated stylesheet. The semantic layout primitives
  (`fl-stack`, `fl-cluster`, `fl-split`, `fl-flank`, `fl-frame`, `fl-grid`)
  handle the layouts that would otherwise need breakpoint variants; the atomic
  utilities are the escape hatch.

  The stylesheet declares `@layer base, components, utilities, focus;`. Utilities
  therefore win over the component theme, while focus treatments stay last.
  """

  @prefix "fl"

  @breakpoints [
    {"sm", "40rem"},
    {"md", "48rem"},
    {"lg", "64rem"},
    {"xl", "80rem"},
    {"2xl", "96rem"}
  ]

  @roles ~w(primary secondary neutral info success warning danger dark light)

  @spacing_steps [
    {"0", "0"},
    {"px", "1px"},
    {"xs", "var(--fl-spacing-xs)"},
    {"sm", "var(--fl-spacing-sm)"},
    {"md", "var(--fl-spacing-md)"},
    {"lg", "var(--fl-spacing-lg)"},
    {"xl", "var(--fl-spacing-xl)"},
    {"2xl", "var(--fl-spacing-2xl)"},
    {"3xl", "var(--fl-spacing-3xl)"}
  ]

  @container_sizes ~w(xs sm md lg xl 2xl 3xl 4xl 5xl 6xl 7xl)

  @doc "The class-name prefix used by every utility."
  def prefix, do: @prefix

  @doc "The named breakpoints, as `{name, min-width}` pairs."
  def breakpoints, do: @breakpoints

  @doc """
  Returns the complete utility stylesheet.

  Pass `reset: false` to omit the base reset. The reset is small but makes
  border utilities predictable: it sets the initial border width to zero.
  """
  def source(opts \\ []) do
    reset? = Keyword.get(opts, :reset, true)

    body =
      families()
      |> Enum.map_join("\n\n", &family_css/1)

    """
    /* FlintUI utilities. Generated by `mix flint.utilities`; edit
     * `FlintUI.Utilities` and regenerate instead of editing this file.
     *
     * Classes are prefixed `fl-` and read the `--fl-*` tokens. Import this
     * stylesheet after `flint.css`; the layer order below makes either order
     * safe. The `focus` layer stays last so focus treatments win.
     */
    @layer base, components, utilities, focus;

    #{if reset?, do: reset_css(), else: ""}

    @layer utilities {
    #{body}
    }
    """
    |> String.trim_trailing()
    |> Kernel.<>("\n")
  end

  @doc """
  Returns the utility families in stylesheet and documentation order.

  Each family carries its title, description, and the classes it emits. The
  docs reference is rendered from this data, so it cannot drift from the
  generated CSS.
  """
  def families do
    [
      family(:layout, "Layout primitives", layout_description(), layout_utilities(),
        css: layout_css()
      ),
      family(:container, "Containers", container_description(), container_utilities(),
        css: container_css()
      ),
      family(:display, "Display and visibility", display_description(), display_utilities()),
      family(:position, "Position and layering", position_description(), position_utilities()),
      family(:flex, "Flexbox", flex_description(), flex_utilities()),
      family(:grid, "Grid", grid_description(), grid_utilities()),
      family(:spacing, "Spacing", spacing_description(), spacing_utilities()),
      family(:sizing, "Sizing", sizing_description(), sizing_utilities()),
      family(:typography, "Typography", typography_description(), typography_utilities()),
      family(:colors, "Color", color_description(), color_utilities()),
      family(:borders, "Borders and radius", border_description(), border_utilities()),
      family(:effects, "Effects", effect_description(), effect_utilities()),
      family(:responsive, "Responsive display", responsive_description(), responsive_utilities(),
        css: responsive_css()
      )
    ]
  end

  @doc """
  Returns every emitted class as a flat list.

  Each entry is `%{class, declaration, family}`. The docs reference uses this
  list directly.
  """
  def classes do
    for family <- families(),
        utility <- family.utilities do
      Map.put(utility, :family, family.id)
    end
  end

  defp family(id, title, description, utilities, opts \\ []) do
    %{
      id: id,
      title: title,
      description: description,
      utilities: utilities,
      css: Keyword.get(opts, :css) || generated_css(utilities)
    }
  end

  defp generated_css(utilities) do
    Enum.map_join(utilities, "\n", fn %{class: class, declaration: declaration} ->
      "  .#{class} { #{declaration} }"
    end)
  end

  defp family_css(%{title: title, css: css}) do
    "  /* #{title} */\n" <> css
  end

  defp util(class, declaration), do: %{class: class, declaration: declaration}

  defp desc(string) do
    string
    |> String.trim()
    |> String.replace(~r/\s+/, " ")
  end

  # Reset --------------------------------------------------------------------

  defp reset_css do
    """
    @layer base {
      *,
      ::before,
      ::after {
        box-sizing: border-box;
        border-width: 0;
        border-style: solid;
        border-color: currentColor;
      }

      body {
        margin: 0;
      }
    }
    """
    |> String.trim_trailing()
  end

