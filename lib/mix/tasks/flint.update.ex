if Code.ensure_loaded?(Igniter) do
  defmodule Mix.Tasks.Flint.Update do
    @shortdoc "Refreshes generated styled components from the library"

    @moduledoc """
    Refreshes the styled components generated by `mix flint.add`.

        mix flint.update
        mix flint.update button toggle
        mix flint.update --force
        mix flint.update --no-theme

    Each generated function carries a marker with its component name, the
    generated-wrapper contract version, the library version, the number of
    top-level statements in its body, and a hash of the body. The task
    regenerates each marked component and replaces the whole block: `@doc`,
    attributes, slots, the public function, and private helpers. The statement
    count keeps code you added below the wrapper out of the block.

    Only wrappers generated by an older library version or wrapper API are
    refreshed, so an up-to-date module is left untouched. That makes renames and
    new defaults from the library a one-command upgrade. A wrapper whose body no
    longer matches its recorded hash is reported and left alone; pass `--force`
    to overwrite it, or to refresh wrappers that already claim the current
    version (useful while developing the library itself). Add `--check` to exit
    non-zero when a refresh is needed, for CI.

    New components are not added. The task reports the ones available in the
    library so you can run `mix flint.add <name>`, and leaves components that
    no longer exist in the library in place.

    The theme and utility stylesheets are regenerated too, so generated code
    and generated CSS stay in step. Pass `--no-theme` to skip that.
    """

    use Igniter.Mix.Task

    alias FlintUI.{Generator, Installer, Styled}

    @impl Igniter.Mix.Task
    def info(_argv, _composing) do
      %Igniter.Mix.Task.Info{
        positional: [{:components, [optional: true, rest: true]}],
        schema: [force: :boolean, theme: :boolean]
      }
    end

    @impl Igniter.Mix.Task
    def igniter(igniter) do
      module = Igniter.Libs.Phoenix.web_module_name(igniter, "Components")
      positional = igniter.args.positional[:components] || []
      force? = igniter.args.options[:force] == true
      theme? = Keyword.get(igniter.args.options, :theme) != false
      {names, unknown} = resolve(positional)

      if unknown == [] do
        update_module(igniter, module, names, force?, theme?)
      else
        Igniter.add_issue(igniter, """
        Unknown component(s): #{Enum.join(unknown, ", ")}.
        Available: #{available()}.
        """)
      end
    end

    defp resolve(positional) do
      Enum.reduce(positional, {[], []}, fn input, {names, unknown} ->
        case Enum.find(Styled.names(), &(Atom.to_string(&1) == input)) do
          nil -> {names, unknown ++ [input]}
          name -> {names ++ [name], unknown}
        end
      end)
    end

    defp available, do: Enum.map_join(Styled.names(), ", ", &to_string/1)

    defp update_module(igniter, module, names, force?, theme?) do
      case Igniter.Project.Module.find_module(igniter, module) do
        {:ok, {igniter, source, _zipper}} ->
          path = Rewrite.Source.get(source, :path)
          content = Rewrite.Source.get(source, :content)
          {:ok, new_content, messages} = update_content(content, names, force?)

          igniter
          |> maybe_write(path, content, new_content)
          |> add_messages(messages)
          |> maybe_theme(theme?)

        {:error, igniter} ->
          Igniter.add_issue(igniter, """
          #{inspect(module)} was not found. Run `mix flint.setup` first, or
          `mix flint.add <component>` to create it.
          """)
      end
    end

    defp maybe_write(igniter, _path, content, content), do: igniter

    defp maybe_write(igniter, path, _content, new_content) do
      igniter
      |> Igniter.update_file(path, fn source ->
        Rewrite.Source.update(source, :content, new_content)
      end)
      |> Igniter.format([path])
      |> sync_markers(path)
    end

    # Formatting happens after the bodies are written, so the marker hashes must
    # be recomputed from the formatted blocks to stay comparable on the next run.
    defp sync_markers(igniter, path) do
      case Rewrite.source(igniter.rewrite, path) do
        {:ok, source} ->
          content = Rewrite.Source.get(source, :content)
          synced = Generator.sync_hashes(content)

          if synced == content do
            igniter
          else
            Igniter.update_file(igniter, path, fn source ->
              Rewrite.Source.update(source, :content, synced)
            end)
          end

        _ ->
          igniter
      end
    end

    defp add_messages(igniter, messages) do
      Enum.reduce(messages, igniter, fn
        {:notice, message}, igniter -> Igniter.add_notice(igniter, message)
        {:warning, message}, igniter -> Igniter.add_warning(igniter, message)
      end)
    end

    defp maybe_theme(igniter, true) do
      igniter
      |> Installer.install_theme_css(on_exists: :overwrite)
      |> Installer.install_utilities_css(on_exists: :overwrite)
    end

    defp maybe_theme(igniter, false), do: igniter

    # The content updater is pure so it can be exercised without writing files.
    # It returns notices and warnings for the caller to surface.
    defp update_content(content, names, force?) do
      lines = String.split(content, "\n")
      blocks = Generator.blocks(content)
      selected = if names == [], do: nil, else: MapSet.new(names, &Atom.to_string/1)
      registered = MapSet.new(Styled.names(), &Atom.to_string/1)
      marked = MapSet.new(blocks, & &1.name)

      plans =
        blocks
        |> Enum.filter(&in_scope?(&1, selected))
        |> Enum.map(&plan(&1, lines, registered, force?))

      replacements = Enum.filter(plans, &(&1.action == :replace))

      new_lines =
        replacements
        |> Enum.sort_by(& &1.block.index, :desc)
        |> Enum.reduce(lines, fn replacement, acc -> replace_block(acc, replacement) end)

      messages =
        plans
        |> Enum.map(& &1.message)
        |> Enum.reject(&is_nil/1)
        |> Kernel.++(unmarked_messages(marked, registered, selected))

      {:ok, Enum.join(new_lines, "\n"), messages}
    end

    defp in_scope?(_block, nil), do: true
    defp in_scope?(block, selected), do: MapSet.member?(selected, block.name)

    defp plan(block, lines, registered, force?) do
      body = Generator.block_body(lines, block)
      pristine? = Generator.body_hash(body) == block.hash
      current? = current_version?(block)

      cond do
        not MapSet.member?(registered, block.name) ->
          %{block: block, action: :keep, message: {:notice, removed_message(block.name)}}

        block.wrapper_api > Generator.wrapper_api() ->
          %{
            block: block,
            action: :keep,
            message:
              {:warning,
               "#{block.name} was generated by a newer wrapper API " <>
                 "(#{block.wrapper_api}, this library provides #{Generator.wrapper_api()}). " <>
                 "Upgrade flint_ui instead of downgrading the wrapper."}
          }

        current? and not force? ->
          %{block: block, action: :keep, message: nil}

        not pristine? and not force? ->
          %{block: block, action: :keep, message: {:warning, edited_message(block)}}

        true ->
          refresh(block)
      end
    end

    # A wrapper is current when it was generated by this library version. Any
    # release that changes wrapper output bumps the version or the wrapper API,
    # so no formatting comparison is needed (and none would be reliable: the
    # host formatter preserves some line-break choices).
    defp current_version?(block) do
      block.wrapper_api == Generator.wrapper_api() and
        block.lib == Generator.library_version()
    end

    defp refresh(block) do
      name = Enum.find(Styled.names(), &(Atom.to_string(&1) == block.name))

      %{
        block: block,
        action: :replace,
        body: Generator.component_source(name),
        message: refresh_message(block)
      }
    end

    defp refresh_message(block) do
      if block.wrapper_api == Generator.wrapper_api() and
           block.lib == Generator.library_version() do
        nil
      else
        {:notice,
         "#{block.name}: refreshed from wrapper API #{block.wrapper_api} to " <>
           "#{Generator.wrapper_api()} (flint_ui #{block.lib} to #{Generator.library_version()})."}
      end
    end

    defp replace_block(lines, %{block: block, body: body}) do
      {head, rest} = Enum.split(lines, block.index)
      {_old, tail} = Enum.split(rest, block.stop - block.index + 1)

      head ++ String.split(body, "\n") ++ tail
    end

    defp edited_message(block) do
      """
      #{block.name} has local changes since it was generated, so it was left
      alone. Run `mix flint.update #{block.name} --force` to overwrite it, or
      merge the new wrapper by hand.
      """
    end

    defp removed_message(name) do
      "#{name} is no longer in the library. Its generated wrapper was left in place."
    end

    defp unmarked_messages(marked, registered, selected) do
      missing =
        registered
        |> MapSet.difference(marked)
        |> maybe_filter_selection(selected)
        |> Enum.sort()

      case missing do
        [] ->
          []

        names ->
          [
            {:notice,
             "Available in the library but not generated in this module: " <>
               Enum.join(names, ", ") <> ". Run `mix flint.add <name>` to add one."}
          ]
      end
    end

    defp maybe_filter_selection(names, nil), do: names

    defp maybe_filter_selection(names, selected) do
      Enum.filter(names, &MapSet.member?(selected, &1))
    end
  end
end
